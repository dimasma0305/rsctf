fn source(container_id: &str, end_time_utc: DateTime<Utc>) -> ServiceSnapshotSource<'_> {
    ServiceSnapshotSource {
        team_service_id: 7,
        container_id,
        end_time_utc,
    }
}

async fn fixture() -> (TestDatabase, PathBuf, LocalBlobStorage, DateTime<Utc>) {
    let db = TestDatabase::new("ad_snapshots").await;
    let pool = &db.pool;
    sqlx::raw_sql(
        r#"
        CREATE TABLE "Files" (
            id SERIAL PRIMARY KEY,
            hash TEXT NOT NULL UNIQUE,
            upload_time_utc TIMESTAMPTZ NOT NULL,
            file_size BIGINT NOT NULL,
            name TEXT NOT NULL,
            reference_count BIGINT NOT NULL
        );
        CREATE TABLE "AdTeamServices" (
            id INTEGER PRIMARY KEY,
            container_id TEXT,
            game_id INTEGER NOT NULL
        );
        CREATE TABLE "AdServiceSnapshots" (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            team_service_id INTEGER NOT NULL UNIQUE,
            local_file_id INTEGER NOT NULL REFERENCES "Files"(id),
            source_container_id TEXT NOT NULL,
            captured_at_utc TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
            expires_at_utc TIMESTAMPTZ,
            CHECK (expires_at_utc IS NULL OR expires_at_utc > captured_at_utc)
        );
        CREATE FUNCTION rsctf_release_ad_service_snapshot_file()
        RETURNS TRIGGER LANGUAGE plpgsql AS $$
        BEGIN
            UPDATE "Files"
               SET reference_count = GREATEST(reference_count - 1, 0)
             WHERE id = OLD.local_file_id;
            RETURN OLD;
        END $$;
        CREATE TRIGGER trg_ad_service_snapshot_release
        AFTER DELETE ON "AdServiceSnapshots"
        FOR EACH ROW
        EXECUTE FUNCTION rsctf_release_ad_service_snapshot_file();
        CREATE TABLE "Attachments" (id INTEGER PRIMARY KEY, local_file_id INTEGER);
        CREATE TABLE "Participations" (id INTEGER PRIMARY KEY, writeup_id INTEGER);
        CREATE TABLE "AspNetUsers" (id INTEGER PRIMARY KEY, avatar_hash TEXT);
        CREATE TABLE "Teams" (id INTEGER PRIMARY KEY, avatar_hash TEXT);
        CREATE TABLE "Games" (id INTEGER PRIMARY KEY, poster_hash TEXT,
            end_time_utc TIMESTAMPTZ NOT NULL);
        CREATE TABLE "Configs" (config_key TEXT PRIMARY KEY, value TEXT);
        CREATE TABLE "GameChallenges" (
            id INTEGER PRIMARY KEY, original_archive_blob_path TEXT
        );
        INSERT INTO "Games" VALUES (1, NULL, clock_timestamp() - interval '1 hour');
        INSERT INTO "AdTeamServices" VALUES (7, 'runtime-7', 1);
        "#,
    )
    .execute(pool)
    .await
    .unwrap();
    crate::services::blob_refs::test_support::install_operation_tables(pool).await;

    let root = std::env::temp_dir().join(format!("rsctf-ad-snapshot-{}", Uuid::new_v4().simple()));
    std::fs::create_dir_all(&root).unwrap();
    let storage = LocalBlobStorage::new(&root);
    let end = sqlx::query_scalar(r#"SELECT end_time_utc FROM "Games" WHERE id = 1"#)
        .fetch_one(pool)
        .await
        .unwrap();
    (db, root, storage, end)
}

#[tokio::test]
#[ignore = "requires PostgreSQL via RSCTF_TEST_DATABASE_URL"]
async fn final_snapshot_is_idempotent_downloadable_and_expired_exactly_once() {
    let (db, root, storage, end) = fixture().await;
    let pool = db.pool.clone();
    let bytes = b"final service filesystem";
    let expires = Utc::now() + chrono::Duration::days(7);
    let first = store_service_snapshot(
        &pool,
        &storage,
        source("runtime-7", end),
        Some(expires),
        "service-7.tar",
        bytes,
    )
    .await
    .unwrap()
    .unwrap();
    let second = store_service_snapshot(
        &pool,
        &storage,
        source("runtime-7", end),
        Some(expires),
        "service-7.tar",
        bytes,
    )
    .await
    .unwrap()
    .unwrap();
    assert_eq!(first.id, second.id);
    assert_eq!(storage.load(&first.hash).await.unwrap(), bytes);
    assert_eq!(
        sqlx::query_scalar::<_, i64>(r#"SELECT reference_count FROM "Files" WHERE hash = $1"#,)
            .bind(&first.hash)
            .fetch_one(&pool)
            .await
            .unwrap(),
        1
    );

    sqlx::query(
        r#"UPDATE "AdServiceSnapshots"
              SET captured_at_utc = now() - interval '2 days',
                  expires_at_utc = now() - interval '1 day'
            WHERE id = $1"#,
    )
    .bind(first.id)
    .execute(&pool)
    .await
    .unwrap();
    assert_eq!(
        purge_expired_service_snapshots(&pool, &storage, 16)
            .await
            .unwrap(),
        1
    );
    assert!(load_service_snapshot(&pool, 7).await.unwrap().is_none());
    assert!(!storage.exists(&first.hash).await);
    assert_eq!(
        sqlx::query_scalar::<_, i64>(r#"SELECT COUNT(*) FROM "Files""#)
            .fetch_one(&pool)
            .await
            .unwrap(),
        0
    );

    db.close().await;
    drop(storage);
    std::fs::remove_dir_all(root).unwrap();
}

struct ControlledStorage {
    local: LocalBlobStorage,
    hold_next: AtomicBool,
    fail_next: AtomicBool,
    started: tokio::sync::Notify,
    resume: tokio::sync::Notify,
}

impl ControlledStorage {
    fn new(local: LocalBlobStorage) -> Self {
        Self {
            local,
            hold_next: AtomicBool::new(false),
            fail_next: AtomicBool::new(false),
            started: tokio::sync::Notify::new(),
            resume: tokio::sync::Notify::new(),
        }
    }
}

#[async_trait::async_trait]
impl BlobStorage for ControlledStorage {
    async fn store(&self, name: &str, bytes: &[u8]) -> AppResult<crate::storage::StoredBlob> {
        if self.hold_next.swap(false, Ordering::SeqCst) {
            self.started.notify_one();
            self.resume.notified().await;
        }
        if self.fail_next.swap(false, Ordering::SeqCst) {
            return Err(AppError::unavailable("injected snapshot storage failure"));
        }
        self.local.store(name, bytes).await
    }
    async fn load(&self, hash: &str) -> AppResult<Vec<u8>> {
        self.local.load(hash).await
    }
    async fn delete(&self, hash: &str) -> AppResult<()> {
        self.local.delete(hash).await
    }
    async fn exists(&self, hash: &str) -> bool {
        self.local.exists(hash).await
    }
}

async fn assert_owned(pool: &PgPool, snapshot: &ServiceSnapshotBlob) {
    let row: (i64, String, i64) = sqlx::query_as(
        r#"SELECT snapshot.id, file.hash, file.reference_count FROM "AdServiceSnapshots" snapshot
            JOIN "Files" file ON file.id = snapshot.local_file_id WHERE snapshot.team_service_id = 7"#)
        .fetch_one(pool).await.unwrap();
    assert_eq!(row, (snapshot.id, snapshot.hash.clone(), 1));
}

#[tokio::test]
#[ignore = "requires PostgreSQL via RSCTF_TEST_DATABASE_URL"]
async fn extended_event_and_replaced_runtime_get_new_final_snapshots_without_losing_old_on_failure()
{
    let (db, root, local, end) = fixture().await;
    let storage = ControlledStorage::new(local);
    let first = store_service_snapshot(
        &db.pool,
        &storage,
        source("runtime-7", end),
        None,
        "first.tar",
        b"first final state",
    )
    .await
    .unwrap()
    .unwrap();
    // Model a previous capture after its original end and an extension whose
    // new end has now passed. The original snapshot must remain owned but hidden.
    sqlx::query(r#"UPDATE "AdServiceSnapshots" SET captured_at_utc = $1 WHERE id = $2"#)
        .bind(end + chrono::Duration::minutes(1))
        .bind(first.id)
        .execute(&db.pool)
        .await
        .unwrap();
    let later_end = sqlx::query_scalar::<_, DateTime<Utc>>(
        r#"UPDATE "Games" SET end_time_utc = end_time_utc + interval '30 minutes'
            WHERE id = 1 RETURNING end_time_utc"#,
    )
    .fetch_one(&db.pool)
    .await
    .unwrap();
    assert!(load_service_snapshot(&db.pool, 7).await.unwrap().is_none());
    assert!(available_service_snapshots(&db.pool, &[7])
        .await
        .unwrap()
        .is_empty());
    storage.fail_next.store(true, Ordering::SeqCst);
    assert!(store_service_snapshot(
        &db.pool,
        &storage,
        source("runtime-7", later_end),
        None,
        "second.tar",
        b"second final state"
    )
    .await
    .is_err());
    assert_owned(&db.pool, &first).await;
    assert_eq!(
        storage.load(&first.hash).await.unwrap(),
        b"first final state"
    );

    let (one, two) = tokio::join!(
        store_service_snapshot(
            &db.pool,
            &storage,
            source("runtime-7", later_end),
            None,
            "second.tar",
            b"second final state"
        ),
        store_service_snapshot(
            &db.pool,
            &storage,
            source("runtime-7", later_end),
            None,
            "second.tar",
            b"concurrent second final state"
        )
    );
    let second = one.unwrap().unwrap();
    assert_eq!(second.id, two.unwrap().unwrap().id);
    assert_ne!(first.id, second.id);
    assert_owned(&db.pool, &second).await;
    assert!(!storage.exists(&first.hash).await);
    assert_eq!(
        available_service_snapshots(&db.pool, &[7]).await.unwrap(),
        HashSet::from([7])
    );

    sqlx::query(r#"UPDATE "AdTeamServices" SET container_id = 'runtime-8' WHERE id = 7"#)
        .execute(&db.pool)
        .await
        .unwrap();
    assert!(load_service_snapshot(&db.pool, 7).await.unwrap().is_none());
    assert!(available_service_snapshots(&db.pool, &[7])
        .await
        .unwrap()
        .is_empty());
    assert!(matches!(
        store_service_snapshot(
            &db.pool,
            &storage,
            source("runtime-7", later_end),
            None,
            "stale.tar",
            b"stale"
        )
        .await,
        Err(AppError::Conflict(_))
    ));
    let third = store_service_snapshot(
        &db.pool,
        &storage,
        source("runtime-8", later_end),
        None,
        "third.tar",
        b"replacement runtime state",
    )
    .await
    .unwrap()
    .unwrap();
    assert_owned(&db.pool, &third).await;
    assert_ne!(second.id, third.id);
    assert!(!storage.exists(&second.hash).await);
    sqlx::query(r#"UPDATE "AdTeamServices" SET container_id = NULL WHERE id = 7"#)
        .execute(&db.pool)
        .await
        .unwrap();
    assert_eq!(
        load_service_snapshot(&db.pool, 7)
            .await
            .unwrap()
            .unwrap()
            .id,
        third.id
    );
    db.close().await;
    tokio::fs::remove_dir_all(root).await.unwrap();
}

#[tokio::test]
#[ignore = "requires PostgreSQL via RSCTF_TEST_DATABASE_URL"]
async fn snapshot_publication_revalidates_event_and_runtime_after_slow_storage_and_cancellation() {
    let (db, root, local, end) = fixture().await;
    let storage = Arc::new(ControlledStorage::new(local));
    let first = store_service_snapshot(
        &db.pool,
        storage.as_ref(),
        source("runtime-7", end),
        None,
        "first.tar",
        b"retained final state",
    )
    .await
    .unwrap()
    .unwrap();
    sqlx::query(r#"UPDATE "AdTeamServices" SET container_id = 'runtime-8' WHERE id = 7"#)
        .execute(&db.pool)
        .await
        .unwrap();

    for mutation in ["event", "runtime", "cancel"] {
        storage.hold_next.store(true, Ordering::SeqCst);
        let pool = db.pool.clone();
        let pending_storage = storage.clone();
        let pending = tokio::spawn(async move {
            store_service_snapshot(
                &pool,
                pending_storage.as_ref(),
                source("runtime-8", end),
                None,
                "pending.tar",
                mutation.as_bytes(),
            )
            .await
        });
        tokio::time::timeout(
            std::time::Duration::from_secs(3),
            storage.started.notified(),
        )
        .await
        .expect("upload never started");
        match mutation {
            "event" => {
                sqlx::query(r#"UPDATE "Games" SET end_time_utc = clock_timestamp() + interval '1 hour' WHERE id = 1"#)
                    .execute(&db.pool).await.unwrap();
            }
            "runtime" => {
                sqlx::query(
                    r#"UPDATE "AdTeamServices" SET container_id = 'runtime-9' WHERE id = 7"#,
                )
                .execute(&db.pool)
                .await
                .unwrap();
            }
            _ => pending.abort(),
        }
        if mutation == "cancel" {
            assert!(pending.await.unwrap_err().is_cancelled());
        } else {
            storage.resume.notify_one();
            assert!(matches!(pending.await.unwrap(), Err(AppError::Conflict(_))));
        }
        assert_owned(&db.pool, &first).await;
        assert_eq!(
            storage.load(&first.hash).await.unwrap(),
            b"retained final state"
        );
        sqlx::query(r#"UPDATE "Games" SET end_time_utc = $1 WHERE id = 1"#)
            .bind(end)
            .execute(&db.pool)
            .await
            .unwrap();
        sqlx::query(r#"UPDATE "AdTeamServices" SET container_id = 'runtime-8' WHERE id = 7"#)
            .execute(&db.pool)
            .await
            .unwrap();
    }
    let recovered = store_service_snapshot(
        &db.pool,
        storage.as_ref(),
        source("runtime-8", end),
        None,
        "recovered.tar",
        b"recovered final state",
    )
    .await
    .unwrap()
    .unwrap();
    assert_owned(&db.pool, &recovered).await;
    assert_ne!(first.id, recovered.id);
    assert!(!storage.exists(&first.hash).await);
    db.close().await;
    tokio::fs::remove_dir_all(root).await.unwrap();
}
